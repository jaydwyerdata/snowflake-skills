CREATE OR REPLACE TABLE SHARED.GOVERNED_STOCK_MOVEMENTS (
    MOVEMENT_ID    INTEGER      NOT NULL,
    PRODUCT_ID     VARCHAR(20)  NOT NULL,
    SUPPLIER_ID    VARCHAR(20)  NOT NULL,
    WAREHOUSE_CODE VARCHAR(10),
    QUANTITY       INTEGER,
    MOVEMENT_TYPE  VARCHAR(10),
    MOVEMENT_DATE  DATE,
    MAPPING_KEY    VARCHAR(100),
    REMOVED_AT     TIMESTAMP_NTZ,
    REFRESHED_AT   TIMESTAMP_NTZ NOT NULL,
    PRIMARY KEY (MOVEMENT_ID)
);

-- ============================================================
-- B. GOVERNANCE TABLES
-- ============================================================

-- Access mappings: which key maps to which role
CREATE OR REPLACE TABLE GOVERNANCE.ACCESS_MAPPING (
    MAPPING_KEY VARCHAR(100)  NOT NULL,
    ROLE_NAME   VARCHAR(256)  NOT NULL,
    CREATED_AT  TIMESTAMP_NTZ NOT NULL,
    PRIMARY KEY (MAPPING_KEY, ROLE_NAME)
);

-- Durable pair assignments (business-grain, survives refresh)
CREATE OR REPLACE TABLE GOVERNANCE.PAIR_ASSIGNMENTS (
    PRODUCT_ID       VARCHAR(20)  NOT NULL,
    SUPPLIER_ID      VARCHAR(20)  NOT NULL,
    MAPPING_KEY      VARCHAR(100) NOT NULL,
    ASSIGNED_AT      TIMESTAMP_NTZ NOT NULL,
    ASSIGNED_BY_RUN_ID INTEGER    NOT NULL,
    PRIMARY KEY (PRODUCT_ID, SUPPLIER_ID)
);

-- Key registry with blocked flag and generation
CREATE OR REPLACE TABLE GOVERNANCE.V2_KEYS (
    MAPPING_KEY VARCHAR(100)  NOT NULL PRIMARY KEY,
    BLOCKED     BOOLEAN       NOT NULL DEFAULT FALSE,
    GENERATION  INTEGER       NOT NULL DEFAULT 1,
    CREATED_AT  TIMESTAMP_NTZ NOT NULL,
    UPDATED_AT  TIMESTAMP_NTZ NOT NULL
);

-- Run log
-- Run IDs come from an explicitly ORDERed sequence and are taken BEFORE the insert. New AUTOINCREMENT
-- columns default to NOORDER (Snowflake behaviour change 2024_01), so MAX(RUN_ID) after an insert
-- is not guaranteed to be the row just inserted.
CREATE OR REPLACE SEQUENCE GOVERNANCE.RUN_ID_SEQ START = 1 INCREMENT = 1 ORDER;
CREATE OR REPLACE TABLE GOVERNANCE.V2_RUNS (
    RUN_ID     INTEGER NOT NULL,
    OPERATION  VARCHAR(20)  NOT NULL,
    FILENAME   VARCHAR(256),
    STARTED_AT TIMESTAMP_NTZ NOT NULL,
    COMPLETED_AT TIMESTAMP_NTZ,
    STATUS     VARCHAR(20)  NOT NULL DEFAULT 'RUNNING',
    RESULT_SUMMARY VARIANT,
    ACTOR      VARCHAR(256) NOT NULL,
    PRIMARY KEY (RUN_ID)
);

-- Logical requests (one per unique pair+key)
CREATE OR REPLACE TABLE GOVERNANCE.V2_REQUESTS (
    REQUEST_ID INTEGER AUTOINCREMENT ORDER NOT NULL,
    RUN_ID     INTEGER      NOT NULL,
    PRODUCT_ID VARCHAR(20),
    SUPPLIER_ID VARCHAR(20),
    MAPPING_KEY VARCHAR(100),
    ROLE_NAME  VARCHAR(256),
    STATUS     VARCHAR(20)  NOT NULL,
    REASON     VARCHAR(1000),
    CREATED_AT TIMESTAMP_NTZ NOT NULL,
    RESOLVED_AT TIMESTAMP_NTZ,
    RESOLVED_BY_RUN_ID INTEGER,
    PRIMARY KEY (REQUEST_ID)
);

-- Submission observations (one per physical CSV row)
CREATE OR REPLACE TABLE GOVERNANCE.V2_SUBMISSIONS (
    SUBMISSION_ID INTEGER AUTOINCREMENT ORDER NOT NULL,
    RUN_ID     INTEGER      NOT NULL,
    FILENAME   VARCHAR(256) NOT NULL,
    FILE_ROW_NUM INTEGER    NOT NULL,
    RAW_LINE   VARCHAR(2000),
    PRODUCT_ID VARCHAR(20),
    SUPPLIER_ID VARCHAR(20),
    MAPPING_KEY VARCHAR(100),
    REQUEST_ID INTEGER,
    OUTCOME    VARCHAR(20)  NOT NULL,
    REASON     VARCHAR(1000),
    SUBMITTED_AT TIMESTAMP_NTZ NOT NULL,
    PRIMARY KEY (SUBMISSION_ID)
);

-- Audit log
CREATE OR REPLACE TABLE GOVERNANCE.AUDIT_LOG (
    AUDIT_ID  INTEGER AUTOINCREMENT ORDER NOT NULL,
    RUN_ID    INTEGER,
    OPERATION VARCHAR(30) NOT NULL,
    DETAIL    VARIANT,
    ACTOR     VARCHAR(256) NOT NULL,
    LOGGED_AT TIMESTAMP_NTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (AUDIT_ID)
);

-- Single-writer mutex
CREATE OR REPLACE TABLE GOVERNANCE.V2_MUTEX (
    LOCK_KEY        VARCHAR(1)    NOT NULL DEFAULT 'X',
    TOKEN           VARCHAR(50)   NOT NULL,
    OWNER_SESSION   VARCHAR(100)  NOT NULL,
    ACQUIRED_AT     TIMESTAMP_NTZ NOT NULL,
    PRIMARY KEY (LOCK_KEY)
);

