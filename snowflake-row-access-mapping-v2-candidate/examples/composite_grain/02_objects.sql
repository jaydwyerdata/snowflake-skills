-- ============================================================
-- D. ROW ACCESS POLICY
-- ============================================================
CREATE OR REPLACE ROW ACCESS POLICY SHARED.ROW_ACCESS_FILTER
AS (row_key VARCHAR, row_removed_at TIMESTAMP_NTZ)
RETURNS BOOLEAN ->
    IS_ROLE_IN_SESSION('RAM_V2_ADMIN')
    OR (
        row_removed_at IS NULL
        AND EXISTS (
            SELECT 1 FROM RAM_V2_EXAMPLE.GOVERNANCE.ACCESS_MAPPING m
            WHERE m.MAPPING_KEY = row_key
              AND IS_ROLE_IN_SESSION(m.ROLE_NAME)
        )
    );

ALTER TABLE SHARED.GOVERNED_STOCK_MOVEMENTS
    ADD ROW ACCESS POLICY SHARED.ROW_ACCESS_FILTER
    ON (MAPPING_KEY, REMOVED_AT);

